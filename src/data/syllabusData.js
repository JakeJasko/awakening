export function toRoman(num) {
  const n = Number(num);
  if (!n || n < 1) return String(num || '');
  const lookup = [
    ['L', 50],
    ['XL', 40],
    ['X', 10],
    ['IX', 9],
    ['V', 5],
    ['IV', 4],
    ['I', 1]
  ];
  let result = '';
  let remaining = n;
  for (const [roman, value] of lookup) {
    while (remaining >= value) {
      result += roman;
      remaining -= value;
    }
  }
  return result;
}

